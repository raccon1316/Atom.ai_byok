// share.js — Share the card: Slack Block Kit, Slack mrkdwn, CRM note.
// Pure + dependency-free: works in extension SW and in Node tests.
// No chrome.*, no network here — the SW POSTs; the popup copies.
//
// payload: {
//   yourCompany, competitor, verifiedDate,
//   pricing, features, targetAudience, recentNews,   // first competitor facts
//   objections: [{objection, theirClaim, counterArgument, sourceUrl, verification}],
//   winStats: {won, lost, winReasons: [], lossReasons: []}
// }
//
// Deviation note (spec honesty): the battle-card data model has no explicit
// howWeWin / landmines blocks (Deal Room does). Share derives:
//   howWeWin  ← win/loss wins' rep-cited reasons (+ profile positioning fallback)
//   theirStrengths ← competitor extraction `features`
//   landmines (Watch for) ← objections' theirClaim (what wins for them)

export const SHARE_FOOTER = (verifiedDate) => `Generated by Atom.AI — verified ${verifiedDate || 'unknown'}`;

export function normalizeShareInput(payload = {}) {
  const competitor = String(payload.competitor || 'competitor').trim();
  const yourCompany = String(payload.yourCompany || 'us').trim();
  const verifiedDate = String(payload.verifiedDate || '').trim();
  const pricing = String(payload.pricing || '').trim().substring(0, 200);
  const features = String(payload.features || '').trim().substring(0, 300);
  const targetAudience = String(payload.targetAudience || '').trim().substring(0, 200);
  const objections = (Array.isArray(payload.objections) ? payload.objections : [])
    .filter((o) => o && typeof o === 'object' && String(o.objection || '').trim())
    .slice(0, 3)
    .map((o) => ({
      objection: String(o.objection).trim().substring(0, 220),
      theirClaim: String(o.theirClaim || '').trim().substring(0, 220),
      counterArgument: String(o.counterArgument || '').trim().substring(0, 220),
      sourceUrl: String(o.sourceUrl || '').trim(),
      verification: o.verification === 'verified' ? 'verified' : 'inferred',
    }));
  const ws = payload.winStats && typeof payload.winStats === 'object' ? payload.winStats : {};
  const winStats = {
    won: Number(ws.won || 0),
    lost: Number(ws.lost || 0),
    winReasons: (Array.isArray(ws.winReasons) ? ws.winReasons : []).map((r) => String(r).trim().substring(0, 120)).filter(Boolean).slice(0, 5),
    lossReasons: (Array.isArray(ws.lossReasons) ? ws.lossReasons : []).map((r) => String(r).trim().substring(0, 120)).filter(Boolean).slice(0, 5),
  };
  return { yourCompany, competitor, verifiedDate, pricing, features, targetAudience, objections, winStats };
}

// howWeWin text: rep-cited win reasons, else positioning, else fallback.
export function howWeWinText(p) {
  const n = p.winStats;
  if (n.won > 0 && n.winReasons.length) {
    return `Reps cited: ${n.winReasons.join(', ')}.`;
  }
  if (p.features) return `Strong fit vs their gaps: ${p.features}`;
  return 'See the card table for the current comparison.';
}

// landmines: what wins for them (from objection claims).
export function landmineTexts(p) {
  return p.objections
    .filter((o) => o.theirClaim)
    .map((o) => o.theirClaim);
}

// ---------------------------------------------------------------------------
// Slack Block Kit
// ---------------------------------------------------------------------------
export function buildSlackBlocks(payload) {
  const p = normalizeShareInput(payload);
  const blocks = [];
  blocks.push({
    type: 'header',
    text: { type: 'plain_text', text: `Battle card: ${p.yourCompany} vs ${p.competitor}`, emoji: true },
  });

  const how = howWeWinText(p);
  blocks.push({
    type: 'section',
    text: { type: 'mrkdwn', text: `*How we win*\n${how}` },
  });

  if (p.pricing || p.features || p.targetAudience) {
    const lines = [];
    if (p.pricing) lines.push(`*Pricing:* ${p.pricing}`);
    if (p.features) lines.push(`*Their strengths:* ${p.features}`);
    if (p.targetAudience) lines.push(`*Best fit:* ${p.targetAudience}`);
    blocks.push({ type: 'section', text: { type: 'mrkdwn', text: lines.join('\n') } });
  }

  for (const o of p.objections) {
    const tag = o.verification === 'verified' ? '✅ verified from their docs' : 'inferred';
    const section = {
      type: 'section',
      text: { type: 'mrkdwn', text: `*⚔️ ${o.objection}* _(${tag})_\nTheir claim: ${o.theirClaim || 'n/a'}\nCounter: ${o.counterArgument || 'n/a'}` },
    };
    if (/^https?:\/\//i.test(o.sourceUrl)) {
      section.accessory = {
        type: 'button',
        text: { type: 'plain_text', text: 'Source ↗', emoji: true },
        url: o.sourceUrl,
      };
    }
    blocks.push(section);
  }

  const mines = landmineTexts(p);
  if (mines.length) {
    blocks.push({
      type: 'section',
      text: { type: 'mrkdwn', text: `*Watch for (landmines)*\n${mines.map((m) => `• ${m}`).join('\n')}` },
    });
  }

  if (p.winStats.won + p.winStats.lost > 0) {
    blocks.push({
      type: 'section',
      text: { type: 'mrkdwn', text: `*Record vs ${p.competitor}:* ${p.winStats.won}W / ${p.winStats.lost}L` },
    });
  }

  blocks.push({
    type: 'context',
    elements: [{ type: 'mrkdwn', text: SHARE_FOOTER(p.verifiedDate) }],
  });
  return blocks;
}

// ---------------------------------------------------------------------------
// Slack mrkdwn (clipboard)
// ---------------------------------------------------------------------------
export function buildSlackMrkdwn(payload) {
  const p = normalizeShareInput(payload);
  const L = [];
  L.push(`*Battle card: ${p.yourCompany} vs ${p.competitor}*`);
  L.push('');
  L.push(`*How we win*`);
  L.push(howWeWinText(p));
  L.push('');
  if (p.pricing) L.push(`*Pricing:* ${p.pricing}`);
  if (p.features) L.push(`*Their strengths:* ${p.features}`);
  if (p.targetAudience) L.push(`*Best fit:* ${p.targetAudience}`);
  if (p.pricing || p.features || p.targetAudience) L.push('');
  if (p.objections.length) {
    L.push(`*Objections (top ${p.objections.length})*`);
    for (const o of p.objections) {
      const tag = o.verification === 'verified' ? '✅ verified from their docs' : 'inferred';
      const link = /^https?:\/\//i.test(o.sourceUrl) ? ` <${o.sourceUrl}|Source ↗>` : '';
      L.push(`• *${o.objection}* _(${tag})_ — Their claim: ${o.theirClaim || 'n/a'} → Counter: ${o.counterArgument || 'n/a'}.${link}`);
    }
    L.push('');
  }
  const mines = landmineTexts(p);
  if (mines.length) {
    L.push(`*Watch for (landmines)*`);
    for (const m of mines) L.push(`• ${m}`);
    L.push('');
  }
  if (p.winStats.won + p.winStats.lost > 0) {
    L.push(`*Record vs ${p.competitor}:* ${p.winStats.won}W / ${p.winStats.lost}L`);
    L.push('');
  }
  L.push(`_${SHARE_FOOTER(p.verifiedDate)}_`);
  return L.join('\n');
}

// ---------------------------------------------------------------------------
// CRM note (plain text, paste into any CRM)
// ---------------------------------------------------------------------------
export function buildCrmNote(payload) {
  const p = normalizeShareInput(payload);
  const L = [];
  L.push(`Competitive intel: ${p.competitor} (verified ${p.verifiedDate || 'n/a'})`);
  L.push(`Their angle: ${p.features || p.pricing || 'n/a'}`);
  L.push(`Our counters: ${p.objections.length ? p.objections.map((o) => o.counterArgument).join(' | ') : 'n/a'}`);
  const mines = landmineTexts(p);
  L.push(`Watch for: ${mines.length ? mines.join(' | ') : 'n/a'}`);
  const urls = p.objections.map((o) => o.sourceUrl).filter((u) => /^https?:\/\//i.test(u));
  L.push(`Sources: ${urls.length ? urls.join(', ') : 'n/a'}`);
  return L.join('\n');
}